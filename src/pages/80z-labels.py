from figures import cmp2, spec, fig

W, H = 250, 120

def _plot(inner, curve=True):
    grid = "".join(
        f'<line x1="0" y1="{y}" x2="{W}" y2="{y}" stroke="var(--grid)" stroke-width="1"/>'
        for y in (24, 96))
    ln = ('<polyline fill="none" stroke="var(--c1)" stroke-width="2" stroke-linecap="round" '
          'stroke-linejoin="round" points="6,44 34,58 62,40 90,50 118,34 146,42 '
          '174,30 202,38 240,32"/>') if curve else ""
    return (f'<svg viewBox="0 0 {W} {H}" style="width:100%;max-width:{W}px">'
            + grid + ln + inner + '</svg>')

def _t(x, y, s, dim=False, anchor="start"):
    c = "var(--sub)" if dim else "var(--ink2)"
    return (f'<text x="{x}" y="{y}" font-size="8.5" text-anchor="{anchor}" fill="{c}" '
            f'font-family="var(--font-num)" font-weight="600">{s}</text>')

# ① 기본 자리 — 비어 있으면 그대로
base_ok  = _plot(_t(6, 92, "하한 95,000"))
# ② 곡선을 관통 — 하지 않는다
bad_hit  = _plot(_t(6, 47, "상한 105,000"))
# ③ 위로 살짝 — 이렇게
good_up  = _plot(_t(6, 28, "상한 105,000"))
# ④ 멀리 가로로 도망 — 하지 않는다
bad_far  = _plot(_t(120, 47, "상한 105,000"))

# 구역 이름과 겹침
zone_bad = _plot(_t(60, 11, "장전", True, "middle") + _t(6, 14, "상한 105,000"))
zone_ok  = _plot(_t(60, 11, "장전", True, "middle") + _t(6, 30, "상한 105,000"))

# 판 밖 경계 — 칩
chip = _plot(
  '<rect x="4" y="100" width="112" height="14" rx="7" fill="var(--fill)"/>'
  + _t(10, 110, "↓ 하한 95,000 · 847만 아래"))
clipped = _plot(
  f'<line x1="0" y1="116" x2="{W}" y2="116" stroke="var(--c1)" stroke-width="1.5" '
  f'opacity=".5"/>' + _t(6, 113, "하한 95,000"))

